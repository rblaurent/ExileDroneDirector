    baseline_actor = get("CameraPlaybackNativeBaselineActorTransformV1", "transform", 0, 1920)
    break_actor = add_form("break_actor_baseline", "break_transform", 320, 1920); bp.connect(baseline_actor, "CameraPlaybackNativeBaselineActorTransformV1", break_actor, "InTransform")
    body_rotator = add_form("body_rotator", "quat_rotator", 320, 1440); collapse_pin(body_rotator, "Q"); bp.connect(body, "CameraPlaybackNativeInputBodyWorldQuatV1", body_rotator, "Q")
    relative_rotator = add_form("relative_rotator", "quat_rotator", 320, 1600); collapse_pin(relative_rotator, "Q"); bp.connect(relative, "CameraPlaybackNativeInputGimbalRelativeQuatV1", relative_rotator, "Q")
