    apply_guard = builder.add("apply_guard", "branch", 704, 5440); bp.connect(failure, "then", apply_guard, "execute"); bp.connect(*ready, apply_guard, "Condition")

    position = get("CameraPlaybackNativeInputPositionV1", "vector", 0, 1280)
