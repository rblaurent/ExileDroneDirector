    bp.connect(b.entry, "then", guard, "execute")
    bp.connect(active, "CleanFrameActiveV1", guard, "Condition")
    bp.connect(guard, "then", ignored, "execute")
    bp.connect(guard, "else", save_popup, "execute")
    bp.connect(gui_popup, "ReturnValue", query_popup, "self")
    bp.connect(query_popup, "ReturnValue", save_popup, "CleanFrameRestorePopupCategoryV1")
    bp.connect(save_popup, "then", save_hud, "execute")
    bp.connect(gui_hud, "ReturnValue", query_hud, "self")
    bp.connect(query_hud, "ReturnValue", save_hud, "CleanFrameRestoreHUDCategoryV1")
    bp.connect(save_hud, "then", disable_popup, "execute")
    bp.connect(gui_disable_popup, "ReturnValue", disable_popup, "self")
    bp.connect(disable_popup, "then", disable_hud, "execute")
    bp.connect(gui_disable_hud, "ReturnValue", disable_hud, "self")
    bp.connect(disable_hud, "then", pc_cast, "execute")
    bp.connect(owner, "ReturnValue", pc_cast, "Object")
    bp.connect(pc_cast, "then", hud_cast, "execute")
    bp.connect(pc_cast, "As Player Controller", get_hud, "self")
    bp.connect(get_hud, "ReturnValue", hud_cast, "Object")
