"""Build deterministic Clean Frame enter/exit/toggle Blueprint graphs.

The graphs suppress Conan's native HUD through the same GUI-module and ConanHUD
APIs used by FunCombat_PlayerController, while preserving the prior HUD and
Popup category flags.  The mod-owned path preview is hidden, never destroyed.
"""

from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from pathlib import Path


CLIENT_ASSET = (
    "/Game/Mods/ExileDroneDirector/Core/Client/"
    "BPC_EDD_ClientDirector.BPC_EDD_ClientDirector"
)
PLAYER_CONTROLLER = "/Script/CoreUObject.Class'/Script/Engine.PlayerController'"
ACTOR = "/Script/CoreUObject.Class'/Script/Engine.Actor'"


def load_helpers(project_root: Path):
    path = project_root / "tools" / "blueprint" / "Build-WaypointCaptureGraph.py"
    spec = importlib.util.spec_from_file_location("edd_clean_frame_base", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Could not load graph helpers: {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def set_entry(node, graph_name: str) -> None:
    node.text = re.sub(
        r'FunctionReference=\(MemberName="[^"]+"\)',
        f'FunctionReference=(MemberName="{graph_name}")',
        node.text,
        count=1,
    )


def set_default(node, pin_name: str, value: str) -> None:
    def mutate(line: str) -> str:
        if 'DefaultValue="' in line:
            return re.sub(r'DefaultValue="[^"]*"', f'DefaultValue="{value}"', line, count=1)
        return line.replace(",PersistentGuid=", f',DefaultValue="{value}",PersistentGuid=', 1)

    node.mutate_pin(pin_name, mutate)


def retarget_bool_variable(node, old: str, new: str) -> None:
    node.text = re.sub(
        rf'VariableReference=\(MemberName="{re.escape(old)}"[^)]*\)',
        f'VariableReference=(MemberName="{new}",bSelfContext=True)',
        node.text,
        count=1,
    )
    node.text = node.text.replace(f'PinName="{old}"', f'PinName="{new}"')
    node.pins[new] = node.pins.pop(old)


def retarget_self_call(node, name: str) -> None:
    node.text = re.sub(
        r'FunctionReference=\([^)]*\)',
        f'FunctionReference=(MemberName="{name}",bSelfContext=True)',
        node.text,
        count=1,
    )


def retarget_preview_get(node) -> None:
    old = "PathPreviewActorV1"
    node.text = re.sub(
        rf'VariableReference=\(MemberName="{old}"[^)]*\)',
        f'VariableReference=(MemberName="{old}",bSelfContext=True)',
        node.text,
        count=1,
    )


def set_category(node, category: str) -> None:
    set_default(node, "Category", category)


def make_is_category_template(enable_template: str) -> str:
    text = enable_template.replace(
        'MemberName="EnableCategory"', 'MemberName="IsCategoryEnabled"', 1
    )
    text = text.replace("   FunctionReference=", "   bDefaultsToPureFunc=True\n   FunctionReference=", 1)
    lines = []
    for line in text.splitlines():
        if 'PinName="execute"' in line or 'PinName="then"' in line:
            continue
        if 'PinName="Enable"' in line:
            line = line.replace('PinName="Enable"', 'PinName="ReturnValue"', 1)
            line = line.replace(
                'PinToolTip="Enable\\nBoolean"', 'PinToolTip="Return Value\\nBoolean"', 1
            )
            line = line.replace(
                'PinName="ReturnValue",',
                'PinName="ReturnValue",Direction="EGPD_Output",',
                1,
            )
            line = re.sub(r',DefaultValue="[^"]*"', '', line)
            line = re.sub(r',AutogeneratedDefaultValue="[^"]*"', '', line)
        lines.append(line)
    return "\n".join(lines)


def make_actor_hidden_template(enable_template: str) -> str:
    text = enable_template.replace(
        'MemberParent="/Script/CoreUObject.Class\'/Script/ConanSandbox.GUIModuleController\'",MemberName="EnableCategory"',
        'MemberParent="/Script/CoreUObject.Class\'/Script/Engine.Actor\'",MemberName="SetActorHiddenInGame"',
        1,
    )
    lines = []
    for line in text.splitlines():
        if 'PinName="Enable"' in line:
            continue
        if 'PinName="self"' in line:
            line = re.sub(
                r'PinType\.PinSubCategoryObject="[^"]+"',
                f'PinType.PinSubCategoryObject="{ACTOR}"',
                line,
                count=1,
            )
            line = line.replace("GUIModule Controller Object Reference", "Actor Object Reference")
        if 'PinName="Category"' in line:
            line = line.replace('PinName="Category"', 'PinName="bNewHidden"', 1)
            line = line.replace('PinToolTip="Category\\nEGUIModuleCategory Enum"', 'PinToolTip="New Hidden\\nBoolean"', 1)
            line = re.sub(r'PinType\.PinCategory="[^"]+"', 'PinType.PinCategory="bool"', line, count=1)
            line = re.sub(r'PinType\.PinSubCategoryObject="[^"]+"', 'PinType.PinSubCategoryObject=None', line, count=1)
            line = re.sub(r'DefaultValue="[^"]*"', 'DefaultValue="false"', line, count=1)
            line = re.sub(r'AutogeneratedDefaultValue="[^"]*"', 'AutogeneratedDefaultValue="false"', line, count=1)
        lines.append(line)
    return "\n".join(lines)


def make_player_controller_cast_template(hud_cast: str) -> str:
    text = hud_cast.replace(
        "/Script/Engine.BlueprintGeneratedClass'/Game/UI/Data/Blueprints/BaseGameHUD.BaseGameHUD_C'",
        PLAYER_CONTROLLER,
    )
    text = text.replace('PinName="AsBase Game HUD"', 'PinName="As Player Controller"')
    return text


def load_templates(project_root: Path, bp) -> dict[str, str]:
    snippets = project_root / "tools" / "blueprint" / "snippets"
    templates = project_root / "tools" / "blueprint" / "templates"
    enter = bp.read_blocks(snippets / "enter-drone-mode.eddgraph")
    toggle = bp.read_blocks(snippets / "toggle-state.eddgraph")
    event = bp.read_blocks(snippets / "client-director-event-graph.eddgraph")
    preview = bp.read_blocks(snippets / "refresh-path-preview-v1.eddgraph")
    native = bp.read_blocks(templates / "conan-clean-frame-node-forms.eddgraph")
    capture = bp.read_blocks(templates / "waypoint-capture-node-forms.eddgraph")
    enable = bp.find_block(native, r'MemberName="EnableCategory"')
    hud_cast = bp.find_block(native, r"K2Node_DynamicCast")
    return {
        "entry": bp.find_block(capture, r"K2Node_FunctionEntry"),
        "branch": bp.find_block(
            enter,
            r"^Begin Object Class=/Script/BlueprintGraph\.K2Node_IfThenElse\b",
        ),
        "valid": bp.find_block(enter, r'MemberName="IsValid"'),
        "bool_get": bp.find_block(toggle, r'K2Node_VariableGet.*MemberName="DroneModeActive"'),
        "bool_set": bp.find_block(toggle, r'K2Node_VariableSet.*MemberName="DroneModeActive"'),
        "print": bp.find_block(toggle, r'MemberName="PrintString"'),
        "self_call": bp.find_block(event, r'MemberName="StopLinearPlayback"'),
        "get_owner": bp.find_block(event, r'MemberName="GetOwner"'),
        "preview_get": bp.find_block(preview, r'K2Node_VariableGet.*MemberName="PathPreviewActorV1"'),
        "get_gui": bp.find_block(native, r'MemberName="GetGUIModuleController"'),
        "enable_category": enable,
        "is_category": make_is_category_template(enable),
        "get_hud": bp.find_block(native, r'MemberName="GetHUD"'),
        "player_cast": make_player_controller_cast_template(hud_cast),
        "hud_cast": hud_cast,
        "set_hud_visibility": bp.find_block(native, r'MemberName="SetHUDVisibility"'),
        "select_visibility": bp.find_block(native, r"K2Node_Select"),
        "set_actor_hidden": make_actor_hidden_template(enable),
    }


class Builder:
    def __init__(self, bp, templates: dict[str, str], graph_name: str):
        self.bp = bp
        self.templates = templates
        self.nodes = []
        bp.TARGET_ASSET = CLIENT_ASSET
        bp.TARGET_GRAPH = graph_name
        self.entry = self.add("entry", "entry", "K2Node_FunctionEntry_0", 0, 0)
        set_entry(self.entry, graph_name)

    def add(self, key: str, template: str, name: str, x: int, y: int):
        node = self.bp.Node.clone(key, self.templates[template], name, x, y)
        self.nodes.append(node)
        return node

    def bool_get(self, variable: str, x: int, y: int):
        node = self.add(variable + "_get", "bool_get", f"K2Node_VariableGet_{len(self.nodes)}", x, y)
        retarget_bool_variable(node, "DroneModeActive", variable)
        return node

    def bool_set(self, variable: str, x: int, y: int):
        node = self.add(variable + "_set", "bool_set", f"K2Node_VariableSet_{len(self.nodes)}", x, y)
        retarget_bool_variable(node, "DroneModeActive", variable)
        return node

    def call(self, function: str, x: int, y: int):
        node = self.add(
            function,
            "self_call",
            f"K2Node_CallFunction_Call_{function}_{len(self.nodes)}",
            x,
            y,
        )
        retarget_self_call(node, function)
        return node

    def print(self, text: str, x: int, y: int):
        node = self.add(
            "print_" + str(len(self.nodes)),
            "print",
            f"K2Node_CallFunction_Print_{len(self.nodes)}",
            x,
            y,
        )
        set_default(node, "InString", text)
        return node


def build_enter(bp, templates):
    b = Builder(bp, templates, "EnterCleanFrameV1")
    active = b.bool_get("CleanFrameActiveV1", 0, 224)
    guard = b.add("guard", "branch", "K2Node_IfThenElse_0", 272, 0)
