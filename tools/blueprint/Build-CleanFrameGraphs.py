def build_toggle(bp, templates):
    b = Builder(bp, templates, "ToggleCleanFrameV1")
    active = b.bool_get("CleanFrameActiveV1", 0, 224)
    branch = b.add("branch", "branch", "K2Node_IfThenElse_0", 272, 0)
    exit_call = b.call("ExitCleanFrameV1", 544, -96)
    enter_call = b.call("EnterCleanFrameV1", 544, 128)
    bp.connect(b.entry, "then", branch, "execute")
    bp.connect(active, "CleanFrameActiveV1", branch, "Condition")
    bp.connect(branch, "then", exit_call, "execute")
    bp.connect(branch, "else", enter_call, "execute")
    return b.nodes


def write_graph(nodes, output: Path, *, paste: bool) -> None:
    blocks = []
    for node in nodes:
        if paste and node is nodes[0]:
            continue
        text = node.text
        if paste:
            text = re.sub(r',LinkedTo=\(K2Node_FunctionEntry_0 [0-9A-F]{32},\)', '', text)
        blocks.append(text)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(blocks) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--project-root", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--paste-dir", type=Path)
    args = parser.parse_args()
    bp = load_helpers(args.project_root)
    templates = load_templates(args.project_root, bp)
    graphs = {
        "enter-clean-frame-v1": build_enter(bp, templates),
        "exit-clean-frame-v1": build_exit(bp, templates),
        "toggle-clean-frame-v1": build_toggle(bp, templates),
    }
    for stem, nodes in graphs.items():
        write_graph(nodes, args.output_dir / f"{stem}.eddgraph", paste=False)
        if args.paste_dir:
            write_graph(nodes, args.paste_dir / f"{stem}-paste.eddgraph", paste=True)


if __name__ == "__main__":
    main()
