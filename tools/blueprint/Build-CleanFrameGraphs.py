    save_hud = b.bool_set("CleanFrameRestoreHUDCategoryV1", 1408, 32)

    gui_disable_popup = b.add("gui_disable_popup", "get_gui", "K2Node_CallFunction_4", 1408, 432)
    disable_popup = b.add("disable_popup", "enable_category", "K2Node_CallFunction_5", 1664, 32)
    set_category(disable_popup, "Popup")
    set_default(disable_popup, "Enable", "false")
    gui_disable_hud = b.add("gui_disable_hud", "get_gui", "K2Node_CallFunction_6", 1952, 432)
    disable_hud = b.add("disable_hud", "enable_category", "K2Node_CallFunction_7", 2208, 32)
    set_category(disable_hud, "HUD")
    set_default(disable_hud, "Enable", "false")

    owner = b.add("owner", "get_owner", "K2Node_CallFunction_8", 2208, 384)
    pc_cast = b.add("pc_cast", "player_cast", "K2Node_DynamicCast_0", 2496, 32)
    get_hud = b.add("get_hud", "get_hud", "K2Node_CallFunction_9", 2736, 368)
