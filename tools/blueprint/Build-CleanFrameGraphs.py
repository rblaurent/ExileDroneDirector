    hide_native = b.add("hide_native", "set_hud_visibility", "K2Node_CallFunction_10", 3264, 32)
    set_default(hide_native, "visibility", "Hidden")

    preview = b.add("preview", "preview_get", "K2Node_VariableGet_3", 2992, 464)
