"""Build deterministic Blueprint graphs for bounded draft undo/redo history.

The first milestone stores full value snapshots.  This deliberately favors a
small, auditable transaction boundary over command-specific inverse logic.
Generated paste artifacts omit the native function entry; the live editor must
connect that one exposed execution input before the graph is accepted.
"""

